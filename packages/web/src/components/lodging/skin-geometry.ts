/**
 * Mix a hex colour toward black (amount < 0) or white (amount > 0) by a
 * fraction. Used to derive a skin's shadow/highlight shades from a single
 * per-unit fabric colour.
 */
export function shadeHex(hex: string, amount: number): string {
  const m = /^#?([0-9a-f]{6})$/i.exec(hex.trim());
  if (!m) return hex;
  const n = parseInt(m[1], 16);
  const mix = (c: number) =>
    Math.max(0, Math.min(255, Math.round(amount >= 0 ? c + (255 - c) * amount : c * (1 + amount))));
  const r = mix((n >> 16) & 255);
  const g = mix((n >> 8) & 255);
  const b = mix(n & 255);
  return `#${((1 << 24) | (r << 16) | (g << 8) | b).toString(16).slice(1)}`;
}

/**
 * Clips a 45° hatch line to the w × h box.
 *
 * Hatching is generated by sweeping an offset `d` from -h to w, which means the
 * raw lines stick out past the box by up to h on each side. Konva's
 * `getClientRect` counts those overhanging endpoints, so a Transformer attached
 * to the shape sizes itself to the overhang rather than the shape — selection
 * handles land well outside the visible rectangle. Clipping the geometry rather
 * than the rendering keeps the reported bounds honest.
 *
 * `dir` 1 runs down-right from (d, 0); -1 runs down-left from (d + h, 0).
 * Returns Konva `points`, or null when the line misses the box entirely.
 */
export function hatchSegment(
  d: number,
  w: number,
  h: number,
  dir: 1 | -1 = 1,
): number[] | null {
  if (w <= 0 || h <= 0) return null;
  // Walk the line by s (which equals y), and clamp to where x stays inside.
  const s0 = dir === 1 ? Math.max(0, -d) : Math.max(0, d + h - w);
  const s1 = dir === 1 ? Math.min(h, w - d) : Math.min(h, d + h);
  if (s1 <= s0) return null;
  const x = (s: number) => (dir === 1 ? d + s : d + h - s);
  return [x(s0), s0, x(s1), s1];
}
