/**
 * Pure geometry for map skins. No Konva imports — everything here is
 * unit-testable math that skins.tsx turns into shapes.
 * All outputs are local px, origin at the unit's top-left.
 */

/** Flat-top hexagon inscribed in w×h (the true ShiftPod footprint). */
export function hexagonPoints(wPx: number, hPx: number): number[] {
  const qw = wPx / 4;
  return [
    qw, 0,
    wPx - qw, 0,
    wPx, hPx / 2,
    wPx - qw, hPx,
    qw, hPx,
    0, hPx / 2,
  ];
}

/**
 * Smooth three-lobed outline (mahal tent plan): r(θ) = R(0.80 + 0.20·cos 3θ),
 * one lobe pointing up. Returned as a closed polygon of `steps` vertices.
 */
export function trefoilPoints(wPx: number, hPx: number, steps = 48): number[] {
  const cx = wPx / 2;
  const cy = hPx / 2;
  const R = Math.min(wPx, hPx) / 2;
  const pts: number[] = [];
  for (let i = 0; i < steps; i++) {
    const theta = (i / steps) * Math.PI * 2 - Math.PI / 2; // start at top
    const r = R * (0.8 + 0.2 * Math.cos(3 * (theta + Math.PI / 2)));
    pts.push(cx + r * Math.cos(theta), cy + r * Math.sin(theta));
  }
  return pts;
}

/** Scale a closed polygon toward its centroid: t=1 → unchanged, t=0 → point. */
export function insetPolygon(points: number[], t: number): number[] {
  let cx = 0;
  let cy = 0;
  const n = points.length / 2;
  for (let i = 0; i < points.length; i += 2) {
    cx += points[i];
    cy += points[i + 1];
  }
  cx /= n;
  cy /= n;
  const out: number[] = [];
  for (let i = 0; i < points.length; i += 2) {
    out.push(cx + (points[i] - cx) * t, cy + (points[i + 1] - cy) * t);
  }
  return out;
}

/** Evenly spaced rib coordinates along a length, half a pitch in from each end. */
export function ribPositions(lengthPx: number, pitchPx: number): number[] {
  const out: number[] = [];
  for (let p = pitchPx / 2; p <= lengthPx - pitchPx / 2 + 1e-6; p += pitchPx) out.push(p);
  return out;
}

/** Interior grid line offsets at cell pitch (edges excluded). */
export function gridLinePositions(sizePx: number, cellPx: number): number[] {
  const out: number[] = [];
  for (let p = cellPx; p < sizePx - 1e-6; p += cellPx) out.push(p);
  return out;
}

/** Cell rects tiling w×h at cell pitch; edge cells clamp to the remainder. */
export function latticeCells(
  wPx: number,
  hPx: number,
  cellPx: number,
): { x: number; y: number; w: number; h: number }[] {
  const cells: { x: number; y: number; w: number; h: number }[] = [];
  for (let y = 0; y < hPx - 1e-6; y += cellPx) {
    for (let x = 0; x < wPx - 1e-6; x += cellPx) {
      cells.push({ x, y, w: Math.min(cellPx, wPx - x), h: Math.min(cellPx, hPx - y) });
    }
  }
  return cells;
}

